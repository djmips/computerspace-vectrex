"""Generate postab.inc: absolute-position tables for placing objects on the rotated playfield.

  python postab.py <out.inc>

An object's grid origin (gx, gy) in original pixels (gx -16..271, gy -16..254, so a wrapped copy
just off the field is reachable) becomes one move from the zeroed beam (the centre) at one of a few
move scales, plus a small remainder that the draw loop adds to the first dot move after it (in
FIRST_SCALE units), so positions are exact to a fraction of a pixel. A move's time grows with its
scale, so a near object uses a small scale: the class is the smallest whose reach covers both axes.

  need_y[gx + 16], need_x[gy + 16]: the smallest class (0..3) each axis needs
  pos_y_c[gx + 16]: DB dac, rem for class c   (Vectrex Y from original x)
  pos_x_c[gy + 16]: DB dac, rem for class c   (Vectrex X from original y)
  move_scales: DB the scale of each class
  pos_y_tab / pos_x_tab: DW the class tables
Constants: vxparams.py.
"""
import sys
from vxparams import FIRST_SCALE, DOT_SCALE, MOVE_SCALES, FLIP, units_per_px

DOT_UNITS = units_per_px(FIRST_SCALE)             # remainders go on a segment's first move


def entry(px, scale):
    """(dac, rem) for a move of px pixels at this scale, or None if out of reach."""
    step = 1 / units_per_px(scale)                # pixels per DAC step
    dac = round(px / step)
    if not -127 <= dac <= 127:
        return None
    rem = round((px - dac * step) * DOT_UNITS)
    assert -8 <= rem <= 8, rem
    return dac * FLIP, rem * FLIP


def need(px):
    for c, s in enumerate(MOVE_SCALES):
        if entry(px, s):
            return c
    raise ValueError(px)


out = sys.argv[1]
YS = [gx - 128 for gx in range(-16, 272)]         # pixels from the centre column (x 128)
XS = [gy - 119 for gy in range(-16, 255)]         # pixels from the centre row (119)
L = ["; Generated by tools/postab.py - do not edit.",
     f"FIELD_FLIP          equ      {FLIP}",
     f"FIRST_SCALE         equ      {FIRST_SCALE}",
     f"DOT_SCALE           equ      {DOT_SCALE}",
     "move_scales         DB       " + ", ".join(str(s) for s in MOVE_SCALES),
     "pos_y_tab           DW       " + ", ".join(f"pos_y_{c}" for c in range(len(MOVE_SCALES))),
     "pos_x_tab           DW       " + ", ".join(f"pos_x_{c}" for c in range(len(MOVE_SCALES))),
     "; need_y[gx + 16]: smallest move class for grid origin column gx = -16..271",
     "need_y"]
L += [f"                    DB       {need(p)}" for p in YS]
L += ["; need_x[gy + 16]: smallest move class for grid origin row gy = -16..254", "need_x"]
L += [f"                    DB       {need(p)}" for p in XS]
for c, s in enumerate(MOVE_SCALES):
    L.append(f"; class {c}: scale {s}")
    for name, pts in ((f"pos_y_{c}", YS), (f"pos_x_{c}", XS)):
        L.append(name)
        for p in pts:
            e = entry(p, s) or (0, 0)             # out of reach: never used (need > c)
            L.append(f"                    DB       {e[0]}, {e[1]}")
open(out, "w").write("\n".join(L) + "\n")
print(f"move classes {MOVE_SCALES}: reach " +
      ", ".join(f"{127 / units_per_px(s):.0f} px" for s in MOVE_SCALES))
