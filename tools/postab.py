"""Generate postab.inc: absolute-position tables for placing objects on the rotated playfield.

  python postab.py <out.inc>

An object's grid origin (gx, gy) in original pixels (gx -16..271, gy -16..254, so a wrapped copy
just off the field is reachable) becomes one Moveto_d at MOVE_SCALE plus a small remainder that the
draw loop adds to the object's first dot move. The remainder is in DOT_SCALE units, so positions are
exact to a fraction of a pixel. Constants: vxparams.py.

  pos_y: 288 entries for gx = -16..271: DB dac, rem   (Vectrex Y from original x)
  pos_x: 271 entries for gy = -16..254: DB dac, rem   (Vectrex X from original y)
"""
import sys
from vxparams import MOVE_SCALE, DOT_SCALE, units_per_px

MOVE_STEP = 1 / units_per_px(MOVE_SCALE)          # pixels per DAC step at MOVE_SCALE
DOT_UNITS = units_per_px(DOT_SCALE)               # dot-scale DAC units per pixel


def entry(px):
    dac = round(px / MOVE_STEP)
    assert -127 <= dac <= 127, px
    rem = round((px - dac * MOVE_STEP) * DOT_UNITS)
    assert -8 <= rem <= 8, rem
    return dac, rem


out = sys.argv[1]
L = ["; Generated by tools/postab.py - do not edit.",
     f"MOVE_SCALE          equ      {MOVE_SCALE}",
     f"DOT_SCALE           equ      {DOT_SCALE}",
     "; pos_y[gx + 16]: Moveto Y (dac, rem) for grid origin column gx = -16..271",
     "pos_y"]
for gx in range(-16, 272):
    d, r = entry(gx - 128)                 # pixels from the centre (x 128)
    L.append(f"                    DB       {d}, {r}")
L += ["; pos_x[gy + 16]: Moveto X (dac, rem) for grid origin row gy = -16..254 (field rows 0..238)",
      "pos_x"]
for gy in range(-16, 255):
    d, r = entry(gy - 119)                 # pixels from the centre (row 119)
    L.append(f"                    DB       {d}, {r}")
open(out, "w").write("\n".join(L) + "\n")
print(f"pos_y 288 and pos_x 271 entries; move step {MOVE_STEP:.3f} px, rem in {DOT_UNITS:.2f} units/px")
