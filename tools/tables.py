"""Generate tables.inc: game tables derived from the core's rules.

  python tables.py <out.inc>

missile_tab: per rocket heading (0..31), the rocket missile's velocity (dx, dy) in 1/256 px per
50 Hz frame, x right and y down (memory_board.vhd:1706-1828). The core has 16 missile directions:
  within one heading of N/S/E/W (headings 31,0 / 7,8 / 15,16 / 23,24): straight, 1 px per frame;
  within one heading of a diagonal (3,4 / 11,12 / 19,20 / 27,28): 1 px per frame on both axes;
  the others: 1 px per frame on the major axis, 1 px every second frame on the minor one.
1 px per 59.885 Hz frame = 59.885 px/s = 307/256 px per 50 Hz frame.
"""
import math
import sys

FULL = 307                # 1 px per original frame, in 1/256 px per 50 Hz frame
HALF = 153

out = sys.argv[1]
L = ["; Generated by tools/tables.py - do not edit.",
     f"MISSILE_SPEED       equ      {FULL}                    ; 1/256 px per 50 Hz frame (59.9 px/s)",
     "; missile_tab[heading]: DW dx, dy (1/256 px per frame, x right, y down)",
     "missile_tab"]
for h in range(32):
    a = math.radians(5.625 + 11.25 * h)         # clockwise from up
    sx = 1 if math.sin(a) > 0 else -1
    sy = 1 if -math.cos(a) > 0 else -1           # y grows downward
    k = h % 8                                    # position within the octant pair around an axis
    if h in (31, 0, 15, 16):                     # near N/S: vertical only
        dx, dy = 0, FULL * sy
    elif h in (7, 8, 23, 24):                    # near E/W: horizontal only
        dx, dy = FULL * sx, 0
    elif h in (3, 4, 11, 12, 19, 20, 27, 28):    # near a diagonal
        dx, dy = FULL * sx, FULL * sy
    elif h in (1, 2, 13, 14, 17, 18, 29, 30):    # vertical major
        dx, dy = HALF * sx, FULL * sy
    else:                                        # 5, 6, 9, 10, 21, 22, 25, 26: horizontal major
        dx, dy = FULL * sx, HALF * sy
    # self-test: the quantised direction is within 22.5 deg of the heading
    q = math.degrees(math.atan2(dx, -dy)) % 360
    d = abs((q - math.degrees(a) + 180) % 360 - 180)
    assert d < 23, (h, q, math.degrees(a))
    L.append(f"                    DW       {dx}, {dy}                ; heading {h}")
open(out, "w").write("\n".join(L) + "\n")
print("missile_tab: 32 headings, 16 directions")
