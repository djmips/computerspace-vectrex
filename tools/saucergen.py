"""Generate saucer.inc: the saucer as dot chains, one per phase of its "rotating light".

  python saucergen.py <out.inc> [--anchor=N]

The saucer is a 16 x 8 grid (16 columns of original x, 8 rows of original y), from the core's diode
table (saucer_diode_image.vhd:55-72): row r of the table is column x on screen, bit b is row y.
14 fixed dots. Row 4 also shows the "rotating light" (saucer_diode_image.vhd:83-91,
memory_board.vhd:654-660): it is lit wherever bit 1 of the rocket's horizontal counter is 0, i.e.
2 pixels on, 2 off along the row, shifting as the saucer moves relative to the rocket. Phase p
(0..3) lights the columns x with ((x + p) & 2) == 0. The draw code picks the phase from the two
objects' columns.

Each phase is a segmented dot list (tools/dotlist.py) at DOT_SCALE, re-anchored every N dots
(default 5: the saucer does not rotate, and 5 looked fine on hardware for the ship).
"""
import pathlib
import re
import sys
from vxparams import DOT_SCALE, units_per_px
from dotlist import emit

RTL = pathlib.Path(__import__("os").environ.get(
    "CS_RTL", pathlib.Path(__file__).resolve().parents[2] / "computerspace" / "rtl"))
U = units_per_px(DOT_SCALE)
opts = dict(a[2:].split("=", 1) for a in sys.argv[1:] if a.startswith("--") and "=" in a)
ANCHOR = int(opts.get("anchor", 5))
LIGHT_ROW = 4
LIGHT_FULL = "--light-full" in sys.argv

src = (RTL / "saucer_diode_image.vhd").read_text(encoding="latin-1")
rows = re.findall(r'\("([01]{8})"\)', src[src.index("saucer_image_1 : saucer_image"):])[:16]
assert len(rows) == 16
fixed = [(b, x) for x, bits in enumerate(rows) for b, ch in enumerate(bits) if ch == "1"]  # (row y, col x)
assert len(fixed) == 14, len(fixed)


def chain(pts):
    """Order dots left to right in column bands (a snake through the rows within each column), so
    each segment covers a narrow band of columns: a copy straddling the x seam then skips most
    segments (the two saucers share their x, so both straddle at once)."""
    order = []
    for k, c in enumerate(sorted({p[1] for p in pts})):
        col = sorted((p for p in pts if p[1] == c), key=lambda p: p[0], reverse=k % 2 == 1)
        order += col
    return order


def chain_nn(pts):
    """Order dots nearest-neighbour from the grid corner (unused)."""
    left = list(pts)
    cur, order = (0, 0), []
    while left:
        nxt = min(left, key=lambda p: (max(abs(p[1] - cur[1]), abs(p[0] - cur[0])), p))
        left.remove(nxt)
        order.append(nxt)
        cur = nxt
    return order


out = [a for a in sys.argv[1:] if not a.startswith("--")][0]
L = ["; Generated by tools/saucergen.py - do not edit.",
     f"; Saucer, 4 light phases, dot moves at scale {DOT_SCALE}, re-anchor every {ANCHOR}:"
     " segmented dot lists (tools/dotlist.py).",
     "saucer_tab"]
L += [f"                    DW       saucer_p{p}" for p in range(4)]
for p in range(4):
    # the light's 2-pixel dashes, one dot at each dash centre (Vectrex frame budget: 4 dots, not 8);
    # LIGHT_FULL draws both pixels of every dash, as the original
    if LIGHT_FULL:
        light = [(LIGHT_ROW, x) for x in range(16) if ((x + p) & 2) == 0]
    else:
        # a dash is the pixel pair x, x+1 with (x + p) mod 4 == 0; one past the right edge is clipped
        light = [(LIGHT_ROW, min(15.0, x + 0.5)) for x in range(16) if ((x + p) & 3) == 0]
    dots = sorted(set(fixed) | set(light))
    order = chain(dots)
    seg_lines, _ = emit(f"saucer_p{p}", order, ANCHOR)
    L += seg_lines
pathlib.Path(out).write_text("\n".join(L) + "\n")
print("saucer: 14 fixed dots + the light, 4 phases")
