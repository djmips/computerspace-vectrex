"""Generate digits.inc: the score/time glyphs as raster rows.

  python digits.py <out.inc>

The original shows 7-segment digits from a 7448 decoder (sync_star_board.vhd:392-452). Each glyph
is 8 x 16 pixels with 2-pixel strokes (measured in the simulation of the core): a rows 0-1, b cols
6-7 rows 0-7, c cols 6-7 rows 8-15, d rows 14-15, e cols 0-1 rows 8-15, f cols 0-1 rows 0-7,
g rows 6-7.

The Vectrex sweeps each glyph row along the original's raster direction, one shift-register byte
per row, most significant bit first: a blank slot, then columns 0-6. Column 7 comes from the shift
register holding its last bit until the beam-off write 18 cycles later (columns 6 and 7 are always
the same). Values 0..9, 16 rows each: digit_rows + 16 * value + row.
"""
import sys

SEG = {  # abcdefg from the 7448 table
    0: "1111110", 1: "0110000", 2: "1101101", 3: "1111001", 4: "0110011", 5: "1011011",
    6: "0011111", 7: "1110000", 8: "1111111", 9: "1110011"}


def cells(segs):
    on = set()
    a, b, c, d, e, f, g = (ch == "1" for ch in segs)
    for col in range(8):
        for row in range(16):
            if (a and row <= 1) or (d and row >= 14) or (g and row in (6, 7)) \
               or (b and col >= 6 and row <= 7) or (c and col >= 6 and row >= 8) \
               or (e and col <= 1 and row >= 8) or (f and col <= 1 and row <= 7):
                on.add((row, col))
    return on


out = sys.argv[1]
L = ["; Generated by tools/digits.py - do not edit.",
     "; digit_rows + 16 * value + row: a blank slot, then columns 0-6 (MSB first);",
     "; the shift register's hold draws column 7",
     "digit_rows"]
for v in range(10):
    on = cells(SEG[v])
    assert all(((r, 6) in on) == ((r, 7) in on) for r in range(16)), v
    rows = [sum(1 << (6 - c) for c in range(7) if (r, c) in on) for r in range(16)]
    L.append("                    DB       " + ", ".join(f"${b:02X}" for b in rows) + f"   ; {v}")
# self-test: 0 and 5 match the simulated glyphs
sim0 = ["########", "########"] + ["##....##"] * 12 + ["########", "########"]
sim5 = ["########", "########"] + ["##......"] * 4 + ["########", "########"] + ["......##"] * 6 + \
       ["########", "########"]
for v, sim in ((0, sim0), (5, sim5)):
    got = cells(SEG[v])
    want = {(r, c) for r, line in enumerate(sim) for c, ch in enumerate(line) if ch == "#"}
    assert got == want, v
open(out, "w").write("\n".join(L) + "\n")
print("digits 0..9, 16 rows of 7 columns + the held 8th; 0 and 5 match the simulation")
