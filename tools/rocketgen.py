"""Generate rocket.inc: the 32 rocket headings as dot chains for the Vectrex.

  python rocketgen.py <out.inc> [--diode] [--scale=N] [--prefix=NAME] [--anchor=N]

Game coordinates are the original's: x right 0..255, y down. The playfield is drawn rotated 90°:
original x -> Vectrex Y (up), original y -> Vectrex X (right), with square pixels (vxparams.py).
Dot moves are made at DOT_SCALE, a small scale, so a dot can be placed to a fraction of a pixel.

Two ways to make the 32 headings:
  default   pre-rotated: the core's heading-0 image (base image 0) rotated about its centroid to
            exactly 5.625 + 11.25 h degrees clockwise from up. The core's own headings are flips
            and transposes of 4 base images whose proportions differ (length/width 1.19 to 1.34)
            and whose angles step unevenly (7 to 22 degrees): invisible on the original's soft TV
            picture, plain on the Vectrex's sharp dots.
  --diode   the core's own 32 images (headings.py), exactly as the original draws them.

Each heading is a list:
    DB  count
    DB  dY, dX, row, col, a   ; per dot: beam move (DAC units at DOT_SCALE), grid cell, anchor flag
Every ANCHOR_EVERY-th dot (starting with the first) has a = 1: the draw loop re-anchors (Reset0Ref
and a move to the grid's top-left corner) and dY, dX are from the corner. Other dots have a = 0 and
dY, dX are from the previous dot. On a real Vectrex the error builds up along a chain, so a ship
drawn as one chain of 15 dots goes skinny at the diagonals; re-anchoring every 3 dots fixes it.
row/col (0..15) let the draw loop skip dots that fall outside the field when the rocket straddles an
edge. The ship is centred in the 16x16 grid, which is also its collision box.
TODO: the engine flame dots (rocket_diode_images.vhd:157-178).
"""
import math
import sys
from headings import heading
from vxparams import DOT_SCALE, ANCHOR_EVERY, units_per_px

DIODE = "--diode" in sys.argv
opts = dict(a[2:].split("=", 1) for a in sys.argv[1:] if a.startswith("--") and "=" in a)
DOT_SCALE = int(opts.get("scale", DOT_SCALE))     # override for test carts
PREFIX = opts.get("prefix", "rocket")
ANCHOR = int(opts.get("anchor", ANCHOR_EVERY))
U = units_per_px(DOT_SCALE)       # DAC units per pixel at DOT_SCALE, both axes


def master():
    """Heading-0 image as (row, col) floats, its centroid, and its nose angle (deg clockwise from up)."""
    pts = [(float(r), float(c)) for r, c in heading(0)]
    n = len(pts)
    cr = sum(p[0] for p in pts) / n
    cc = sum(p[1] for p in pts) / n
    srr = sum((p[0] - cr) ** 2 for p in pts) / n
    scc = sum((p[1] - cc) ** 2 for p in pts) / n
    src = sum((p[0] - cr) * (p[1] - cc) for p in pts) / n
    ang = 0.5 * math.atan2(2 * src, scc - srr)              # principal axis, radians (col, row)
    ax, ay = math.cos(ang), math.sin(ang)
    nose = min(pts, key=lambda p: p[0])                     # the nose is on the row-0 side
    if (nose[1] - cc) * ax + (nose[0] - cr) * ay < 0:
        ax, ay = -ax, -ay
    deg = math.degrees(math.atan2(ax, -ay))                 # clockwise from up
    return pts, cr, cc, deg


def rotated(h):
    pts, cr, cc, a0 = master()
    th = math.radians(5.625 + 11.25 * h - a0)
    out = []
    for r, c in pts:
        dc, dr = c - cc, r - cr
        c2 = 7.5 + dc * math.cos(th) - dr * math.sin(th)    # clockwise with rows growing down
        r2 = 7.5 + dc * math.sin(th) + dr * math.cos(th)
        out.append((r2, c2))
    return out


def dots(h):
    """(row, col) float positions of heading h's dots."""
    if DIODE:
        return [(float(r), float(c)) for r, c in heading(h)]
    return rotated(h)


def chain(pts):
    """Order dots nearest-neighbour from the grid corner."""
    left = list(pts)
    cur, order = (0.0, 0.0), []
    while left:
        nxt = min(left, key=lambda p: (max(abs(p[1] - cur[1]), abs(p[0] - cur[0])), p))
        left.remove(nxt)
        order.append(nxt)
        cur = nxt
    return order


out = [a for a in sys.argv[1:] if not a.startswith("--")][0]
lines = ["; Generated by tools/rocketgen.py - do not edit.",
         f"; 32 rocket headings ({'core diode images' if DIODE else 'pre-rotated, 11.25 deg steps'}),"
         f" dot moves at scale {DOT_SCALE}, re-anchor every {ANCHOR}:"
         " count, then (dY, dX, row, col, anchor) per dot.",
         f"{PREFIX}_tab"]
lines += [f"                    DW       {PREFIX}_h{h}" for h in range(32)]
total, worst = 0, 0.0
for h in range(32):
    order = chain(dots(h))
    lines.append(f"{PREFIX}_h{h}")
    lines.append(f"                    DB       {len(order)}")
    prevY = prevX = 0
    got = []
    for i, (r, c) in enumerate(order):
        Y, X = round(c * U), round(r * U)                   # absolute beam position in the grid
        anchor = i % ANCHOR == 0
        if anchor:
            prevY = prevX = 0                               # from the grid corner after a re-anchor
        dY, dX = Y - prevY, X - prevX
        lim = 119 if anchor else 127                        # an anchored move also carries postab's remainder
        assert abs(dY) <= lim and abs(dX) <= lim, (h, i, dY, dX)
        row = min(15, max(0, int(round(r))))
        col = min(15, max(0, int(round(c))))
        lines.append(f"                    DB       {dY}, {dX}, {row}, {col}, {int(anchor)}")
        worst = max(worst, abs(Y - c * U) / U, abs(X - r * U) / U)
        got.append((X / U, Y / U))
        prevY, prevX = Y, X
    total += len(order)
    # self-test: replaying the emitted moves (resetting at each anchor) gives the absolute positions
    ry = rx = 0
    for l, (gx, gy) in zip(lines[-len(order):], got):
        dY, dX, _, _, a = (int(v) for v in l.split("DB")[1].split(","))
        if a:
            ry = rx = 0
        ry += dY
        rx += dX
        assert (rx, ry) == (round(gx * U), round(gy * U)), (h, l)
    # self-test: the replayed chain lands on the intended dots (to the rounding)
    want = dots(h)
    assert len(got) == len(want), h
    for w in want:
        near = min(got, key=lambda g: max(abs(g[0] - w[0]), abs(g[1] - w[1])))
        assert max(abs(near[0] - w[0]), abs(near[1] - w[1])) <= 0.5 / U + 1e-9, (h, w, near)
    if DIODE:
        assert {(round(r), round(c)) for r, c in got} == set(heading(h)), h

if not DIODE:
    # self-test: every heading is the master rotated: the same distances from the centroid
    pts, cr, cc, a0 = master()
    ref = sorted(math.hypot(r - cr, c - cc) for r, c in pts)
    for h in range(32):
        p = rotated(h)
        mr = sum(q[0] for q in p) / len(p)
        mc = sum(q[1] for q in p) / len(p)
        assert max(abs(a - b) for a, b in zip(ref, sorted(math.hypot(r - mr, c - mc) for r, c in p))) < 1e-9
open(out, "w").write("\n".join(lines) + "\n")
print(f"32 headings ({'diode' if DIODE else 'pre-rotated'}), {total} dots at scale {DOT_SCALE} "
      f"({U:.2f} units/px), worst rounding {worst:.3f} px")
